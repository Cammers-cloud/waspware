static int clip_rect(int32_t *x, int32_t *y, uint32_t *width,
                     uint32_t *height)
{
    if (*width == 0 || *height == 0) {
        return 0;
    }

    int64_t left = *x;
    int64_t top = *y;
    int64_t right = left + *width;
    int64_t bottom = top + *height;

    if (right <= 0 || bottom <= 0 ||
        left >= (int64_t)VESA_WIDTH || top >= (int64_t)VESA_HEIGHT) {
        return 0;
    }

    if (left < 0) left = 0;
    if (top < 0) top = 0;
    if (right > VESA_WIDTH) right = VESA_WIDTH;
    if (bottom > VESA_HEIGHT) bottom = VESA_HEIGHT;

    *x = (int32_t)left;
    *y = (int32_t)top;
    *width = (uint32_t)(right - left);
    *height = (uint32_t)(bottom - top);
    return 1;
}

void wm_fill_screen(uint32_t color)
{
    uint32_t *buffer = vesa_backbuffer();
    if (buffer == 0) {
        return;
    }

    for (uint32_t i = 0; i < VESA_WIDTH * VESA_HEIGHT; ++i) {
        buffer[i] = color;
    }
}

void wm_draw_rect(int32_t x, int32_t y, uint32_t width,
                  uint32_t height, uint32_t color)
{
    uint32_t *buffer = vesa_backbuffer();
    if (buffer == 0 || !clip_rect(&x, &y, &width, &height)) {
        return;
    }

    for (uint32_t row = 0; row < height; ++row) {
        uint32_t offset = ((uint32_t)y + row) * VESA_WIDTH + (uint32_t)x;
        for (uint32_t column = 0; column < width; ++column) {
            buffer[offset + column] = color;
        }
    }
}

void wm_draw_char(int32_t x, int32_t y, char character,
                  uint32_t foreground, uint32_t background)
{
    uint32_t *buffer = vesa_backbuffer();
    if (buffer == 0) {
        return;
    }

    uint8_t code = (uint8_t)character;
    if (code < 32 || code > 127) {
        code = '?';
    }

    const uint8_t *glyph = font8x8[code - 32];

    for (uint32_t row = 0; row < FONT_HEIGHT; ++row) {
        int32_t py = y + (int32_t)row;
        if (py < 0 || py >= (int32_t)VESA_HEIGHT) {
            continue;
        }

        for (uint32_t column = 0; column < FONT_WIDTH; ++column) {
            int32_t px = x + (int32_t)column;
            if (px < 0 || px >= (int32_t)VESA_WIDTH) {
                continue;
            }

            uint32_t color =
                (glyph[row] & (0x80U >> column)) ? foreground : background;
            buffer[(uint32_t)py * VESA_WIDTH + (uint32_t)px] = color;
        }
    }
}

void wm_draw_text(int32_t x, int32_t y, const char *text,
                  uint32_t foreground, uint32_t background)
{
    if (text == 0) {
        return;
    }

    int32_t cursor_x = x;
    int32_t cursor_y = y;

    while (*text != '\0') {
        if (*text == '\n') {
            cursor_x = x;
            cursor_y += FONT_HEIGHT;
        } else {
            wm_draw_char(cursor_x, cursor_y, *text, foreground, background);
            cursor_x += FONT_WIDTH;
        }
        ++text;
    }
}

